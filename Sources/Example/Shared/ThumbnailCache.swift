import Foundation

#if canImport(UIKit)
import UIKit
typealias PlatformImage = UIImage
#elseif canImport(AppKit)
import AppKit
typealias PlatformImage = NSImage
#endif

/// A trivial in-memory cache for thumbnail image data, keyed by path and revision.
///
/// This is a playground-grade cache: unbounded and process-lifetime only. It exists purely to
/// avoid re-fetching a thumbnail every time a row scrolls back into view.
actor ThumbnailCache {

	static let shared = ThumbnailCache()

	private var storage: [String: Data] = [:]

	func data(for key: String) -> Data? {
		storage[key]
	}

	func store(_ data: Data, for key: String) {
		storage[key] = data
	}

}
